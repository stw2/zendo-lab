"""04_table.py   results/runs.md from results/measures.json (03_measures.py), the arms' score summaries and files
(02_score.sh), each run's .cmd (start, end, commit) and its run files (calls; calls that reached the thinking budget: local only).
Costs and token counts are not published (docs/conventions.md). Added after the runs, 2026-10-08: it formats the
measures and counts calls; it computes no measure.
"""
import json
from pathlib import Path

E = Path(__file__).resolve().parent.parent
R, S = E / "results" / "runs", E / "results" / "scores"
A8 = Path(__file__).resolve().parents[3] / "experiments/E01-dev-baseline/results"
ARMS = {  # measures.json arm: (run arm, attempt, intervention)
    "A8": ("qwen3.5-4b-mlx", "E1's A8", "none"),
    "show": ("qwen3.5-4b-mlx-show", "A9", "count of consistent rules shown"),
    "force16": ("qwen3.5-4b-mlx-force16", "A10", "submit only after 16 experiments"),
    "force16-show": ("qwen3.5-4b-mlx-force16-show", "A11", "both"),
}
TIERS = ["T1", "T2", "T3", "T4", "T5", "T6"]
NAMED = {"force16 - A8", "show - A8", "force16-show - force16", "force16-show - show"}  # DESIGN.md's pairs


def calls(arm):
    """(calls, reached the thinking budget, ended inside the thought) over the arm's run files."""
    n = cut = thought = 0
    for path in [R / f"{arm}.jsonl", *sorted(R.glob(f"{arm}.part*.jsonl"))]:
        for line in path.read_text().splitlines():
            record = json.loads(line)
            if record.get("type") == "episode":
                for call in record["calls"]:
                    n += 1
                    cut += bool(call.get("backend", {}).get("forced_think_end"))
                    thought += call.get("finish") == "eos_in_thought"
    return n, cut, thought


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}"


def interval(ci, scale=100, digits=1):
    return "–" if not ci else f"[{scale * ci[0]:.{digits}f}, {scale * ci[1]:.{digits}f}]"


def cmd(arm):
    """(start, end, commit) over the arm's .cmd files, in run order."""
    starts, ends, commits = [], [], []
    for path in [R / f"{arm}.cmd", *sorted(R.glob(f"{arm}.part*.cmd"))]:
        for line in path.read_text().splitlines():
            key, _, rest = line.partition(" ")
            if key == "started":
                starts.append(rest)
            elif key == "ended":
                ends.append(rest.split()[0])
            elif key == "zendo-lab":
                commits.append(rest.split()[0][:7])
    return starts, ends, commits


def main():
    m = json.loads((E / "results" / "measures.json").read_text())
    out = ["# E02 runs", "",
           "Generated by `scripts/04_table.py` from `results/measures.json` (`scripts/03_measures.py`) and the score "
           "summaries. Qwen/Qwen3.5-4B bf16 (revision 851bf6e8) on ZendoBench 1.0.0's MLX batch driver, Apple M4 Max "
           "128 GB, 36 games in flight, sampler seed 0, Qwen3.5 thinking sampling (temperature 1.0, top-p 0.95, top-k 20, "
           "min-p 0, presence penalty 1.5), thinking budget 63,487 + 2,048-token answer allowance (65,536 a call). "
           "The dev manifest's first 2 items of each family: 102 games, 92 of them T2-T6. A8 is E1's run "
           "(player `model`) restricted to these games; A9-A11 run through `scripts/intervene.py` (player `agent-tools`). "
           "Win rates in %, 95% CIs; paired differences by task (`compare`'s pairing and t interval).", "",
           "## Configuration", "",
           "| Arm | Attempt | Intervention | zendo-lab | Start (UTC) | End (UTC) | Run files (sha256, bytes) |",
           "|---|---|---|---|---|---|---|"]
    for key, (arm, attempt, what) in ARMS.items():
        if key == "A8":
            files = json.loads((A8 / "scores" / "qwen3.5-4b-mlx.files.json").read_text())
            start, end, commit = "2026-10-05T10:21:31Z", "2026-10-05T22:38:20Z", "1a54652"
        else:
            files = json.loads((S / f"{arm}.files.json").read_text())
            starts, ends, commits = cmd(arm)
            start, end, commit = starts[0], ends[-1], ", ".join(dict.fromkeys(commits))
        runs = "<br>".join(f"`{f['file']}` `{f['sha256'][:16]}…` {f['bytes']:,}" for f in files)
        out.append(f"| `{arm}` | {attempt} | {what} | {commit} | {start} | {end} | {runs} |")
    out += ["", "## Results", "",
            "| Arm | T2-T6 win rate [95% CI] | Seed-only | w0 = 0 band | " + " | ".join(TIERS) + " | Unscored | Malformed (headline) | Calls (reached thinking budget; ended in thought) |",
            "|---|---|---|---|" + "---|" * len(TIERS) + "---|---|---|"]
    for key, (arm, attempt, _) in ARMS.items():
        h = m["arms"][key]["headline"]
        if key == "A8":  # per-tier rows are E1's, over all 460 games: results/scores there; the seed-only baseline is the games'
            seed = pct(json.loads((S / "qwen3.5-4b-mlx-show.score.json").read_text())["context"]["seed_only_map_win"])
            row, unscored, malformed, w0, ncalls = ["–"] * len(TIERS), "–", "–", "–", "–"
        else:
            score = json.loads((S / f"{arm}.score.json").read_text())
            row = [f"{score['tiers'][t]['wins']}/{score['tiers'][t]['scored']}" for t in TIERS]
            unscored = sum(score["tiers"][t]["unscored"] for t in TIERS)
            malformed = pct(score["malformed"]["headline"]["malformed_rate"])
            seed, w0 = pct(score["context"]["seed_only_map_win"]), pct(score["w0"]["pooled"]["w0=0"]["estimate"])
            n, cut, thought = calls(arm)
            ncalls = f"{n:,} ({cut}; {thought})"
        out.append(f"| `{arm}` ({attempt}) | **{pct(h['estimate'])}** {interval(h.get('ci'))} | {seed} | {w0} | " + " | ".join(row)
                   + f" | {unscored} | {malformed} | {ncalls} |")
    out += ["", "A8's per-tier wins on these games: 0 in T2-T6 (its 12 T2-T6 wins over all 430 games fall outside "
            "the subset).", "",
            "## Behaviour (`diagnose`, all 102 games)", "",
            "| Arm | exp/game | bits/exp | EIG | zero-info | repeats | alive at 1st sub | p at 1st sub | subs/game | "
            "contradicting | fits counterex. | certain wrong | conversion (T2-T6 wins / expected) |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for key, (arm, attempt, _) in ARMS.items():
        b = m["arms"][key]["behaviour"]
        conv = "–" if b["conversion"] is None else f"{b['conversion']:.2f} ({b['headline_wins']}/{b['headline_expected_wins']:.1f})"
        out.append(f"| `{arm}` | {b['exp_per_game']:.2f} | {b['bits_per_exp']:.2f} | {b['eig']:.2f} | {b['zero']:.2f} | "
                   f"{b['repeats']} | {b['alive_first']:g} | {b['p_first']:.2f} | {b['subs_per_game']:.2f} | "
                   f"{b['contradicting']} ({pct(b['contradicting_share'])}%) | {b['fits_ce']} | {b['certain_wrong']} | {conv} |")
    out += ["", "## Paired differences (A minus B, the same games)", "",
            "| A - B | T2-T6 wins, points [95% CI] | Experiments a game [95% CI] |", "|---|---|---|"]
    for name, w in m["paired_wins"].items():
        e = m["paired_experiments"][name]
        named = "" if name in NAMED else " (not named in DESIGN.md)"
        out.append(f"| {name}{named} | {pct(w['estimate'])} {interval(w['ci'])} | {e['mean']:.2f} {interval(e['ci'], 1, 2)} |")
    v = m["hypotheses"]
    out += ["", "## Hypotheses (DESIGN.md)", "",
            f"- **Precondition** (force16's median classes alive at the first submission at most 10): "
            f"{v['precondition_force16_narrowed']['alive_first_median']:g}, "
            f"{'holds' if v['precondition_force16_narrowed']['holds'] else 'fails'}.",
            f"- **H1, stopping** (force16 - A8 wins above 0): {pct(v['H_stopping']['difference'])} "
            f"{interval(v['H_stopping']['ci'])}, {v['H_stopping']['verdict']}.",
            f"- **H2, tracking** (force16's contradicting share at least 10%): "
            f"{pct(v['H_tracking']['contradicting_share'])}%, {v['H_tracking']['verdict']}.",
            f"- **H3, uncertainty** (show - A8 experiments a game above 0): {v['H_uncertainty']['mean_difference']:.2f} "
            f"{interval(v['H_uncertainty']['ci'], 1, 2)}, {v['H_uncertainty']['verdict']}.", ""]
    (E / "results" / "runs.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
